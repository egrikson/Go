// Задача 1. Трассировка len и cap
//
// Каждый следующий срез получается из предыдущего:
//
//	s := []int{10, 20, 30, 40, 50, 60}
//	t := s[1:3]
//	u := t[:4]
//	v := u[2:]
//	w := s[:0]
//	x := v[:cap(v)]
//
// СНАЧАЛА впиши в блок «Предсказание» в конце файла все шесть строк вывода
// и только потом запускай. Если предсказание разошлось с выводом — не
// исправляй его, а допиши под ним, где ошибся и почему.
//
// Написать функцию printSlice(name string, s []int), печатающую строку
// в формате ниже, и вызвать её для всех шести срезов.
//
// Ожидаемый вывод: шесть строк вида
//
//	s len=6 cap=6 [10 20 30 40 50 60]
//
// (остальные пять — твоё предсказание).
//
// Ограничения: срезы получать ровно теми выражениями, что выше; печать —
// только через printSlice. append не использовать — он ещё не пройден.
//
// Запуск: go run ./block01/slices-make/task1
package main

import "fmt"

func main() {
	s := []int{10, 20, 30, 40, 50, 60}
	t := s[1:3]
	u := t[:4]
	v := u[2:]
	w := s[:0]
	x := v[:cap(v)]

	printSlice("s", s)
	printSlice("t", t)
	printSlice("u", u)
	printSlice("v", v)
	printSlice("w", w)
	printSlice("x", x)
}

func printSlice(name string, s []int) {
	fmt.Printf("%s len=%d cap=%d %v\n", name, len(s), cap(s), s)
}

