// Задача 4*. Сжатие на месте
//
// Написать функцию compact(s []int) []int: убирает нули, сдвигая
// ненулевые элементы к началу с сохранением порядка, и возвращает срез
// только из них. Новую память не выделять: результат смотрит в тот же
// массив, что и s.
//
// Вход: data := []int{0, 3, 0, 0, 7, 1, 0, 5}
// Плюс два граничных случая: []int{0, 0, 0} и nil.
//
// Ожидаемый вывод:
//
//	Результат: [3 7 1 5] len=4 cap=8
//	Исходный: [3 7 1 5 7 1 0 5]
//	Только нули: [] len=0 cap=3
//	Из nil: [] len=0 cap=0
//
// Ограничения: один проход; без make, append и второго среза или массива;
// результат — срез от s. В блоке «Почему» в конце файла объясни, откуда в
// исходном срезе взялся хвост 7 1 0 5.
//
// Запуск: go run ./block01/slices-make/task4
//
// СНЯТА: задача проверяла алгоритм сжатия, а не тему (make, len/cap) —
// и при этом запрещала make. Решение compact показано Claude по запросу,
// main дописан не до конца. На оценку блока не влияет.
package main

import "fmt"

func main() {
	data := []int{0, 3, 0, 0, 7, 1, 0, 5}

	fmt.Println(compact(data))
}

func compact(s []int) []int {
	k := 0
	for _, v := range s {
		if v != 0 {
			s[k] = v
			k++
		}
	}
	return s[:k]
}

