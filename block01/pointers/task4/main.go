// Задача 4*. Массив указателей и дыры в нём
//
// Со звёздочкой: разобраться, что бывает, когда указателя нет.
//
// Что сделать:
//  1. Завести две переменные: a = 10 и b = 20.
//  2. Завести массив из четырёх указателей на int, в котором первый
//     смотрит на a, третий — на b, а второй и четвёртый равны nil.
//     Тип такого массива записывается [4]*int.
//  3. Пройти массив одним циклом и посчитать две вещи: сумму значений
//     по ненулевым указателям и количество nil.
//
// Ожидаемый вывод:
//
//	сумма: 30, пропущено nil: 2
//
// Ограничения: один цикл; результат печатается одним Printf после
// цикла; разыменовывать указатель, не проверив его, нельзя.
//
// Почему проверка обязательна. Разыменование nil — это не «ноль» и не
// пустое значение, это аварийная остановка программы:
//
//	panic: runtime error: invalid memory address or nil pointer dereference
//
// Сравни с задачей на вариативные функции, где проверка на пустой
// набор была лишней, и с summarize, где она была нужна. Правило то же:
// защищаем то, что действительно падает.
//
// Попробуй ради интереса убрать проверку и запустить. Посмотри, на
// каком элементе программа упадёт и что будет напечатано до падения, —
// это пригодится, когда такая паника встретится в реальном коде.
//
// Запуск: go run ./block01/pointers/task4
package main

import "fmt"

func main() {
	a, b := 10, 20
	p := &a
	q := &b
	data := [4]*int{p, nil, q, nil}

	countNil := 0
	sum := 0

	for _, value := range data {
		if value == nil {
			countNil++
		} else {
			sum += *value
		}
	}

	fmt.Printf("сумма: %d, пропущено nil: %d\n", sum, countNil)
}
