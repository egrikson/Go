// Задача 3. Указатель на элемент массива
//
// Соединяем указатели с массивами. Задача: найти максимум и обнулить
// его на месте, ни разу не запомнив его индекс.
//
// Что сделать:
//  1. Завести массив [5]int{12, 45, 7, 23, 38} и напечатать его.
//  2. Завести указатель maxPtr на ПЕРВЫЙ элемент массива.
//  3. Пройти массив со второго элемента. Если текущий элемент больше
//     того, на что смотрит maxPtr, — переставить maxPtr на него.
//  4. Напечатать найденный максимум (через указатель).
//  5. Записать 0 туда, куда смотрит maxPtr, и напечатать массив снова.
//
// Ожидаемый вывод:
//
//	было:     [12 45 7 23 38]
//	максимум: 45
//	стало:    [12 0 7 23 38]
//
// Ограничения: переменной под индекс максимума НЕТ — только указатель;
// в шаге 5 обращение к массиву по индексу запрещено, пишем через
// maxPtr; массивы печатать через %v, выравнивание повторить точно.
//
// Здесь обе операции из задачи 2 работают вместе и по делу:
// переставляем указатель, пока ищем, и пишем по указателю, когда нашли.
//
// Обрати внимание на последнюю строку вывода: массив изменился, хотя
// имени data в пятом шаге нет. Указатель на элемент — это указатель
// внутрь самого массива, а не на его копию.
//
// Запуск: go run ./block01/pointers/task3
package main

import "fmt"

func main() {
	data := [5]int{12, 45, 7, 23, 38}
	fmt.Println("было:", data)

	maxPtr := &data[0]

	for i := 1; i < len(data); i++ {
		if data[i] > *maxPtr {
			maxPtr = &data[i]
		}
	}

	fmt.Println("максимум:", *maxPtr)
	*maxPtr = 0

	fmt.Println("стало:", data)

}
