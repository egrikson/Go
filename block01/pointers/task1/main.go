// Задача 1. Связь в обе стороны
//
// Разминка: убедиться, что переменная и указатель на неё — это один и
// тот же ящик, в который можно залезть двумя способами.
//
// Что сделать:
//  1. Завести count со значением 7 и указатель ptr на неё.
//  2. Напечатать значение count, тип ptr и значение по ptr.
//  3. Через указатель записать 42 и напечатать count.
//  4. Через ИМЯ переменной записать 100 и напечатать значение по ptr.
//
// Ожидаемый вывод:
//
//	значение count: 7
//	тип ptr:        *int
//	значение по ptr: 7
//	count после *ptr = 42: 42
//	значение по ptr после count = 100: 100
//
// Ограничения: указатель объявить через &; тип печатать глаголом %T;
// адрес НЕ печатать — он каждый раз разный, вывод не сойдётся.
//
// Смысл двух последних строк: связь работает в обе стороны. Меняешь
// через указатель — видно по имени. Меняешь по имени — видно через
// указатель. Копии здесь нет, переменная одна.
//
// Запуск: go run ./block01/pointers/task1
package main

import "fmt"

func main() {
	count := 7
	ptr := &count

	fmt.Println("значение count:", count)
	fmt.Printf("тип ptr: %T\n", ptr)
	fmt.Println("значение по ptr:", *ptr)

	*ptr = 42

	fmt.Println("count после *ptr = 42:", count)

	count = 100

	fmt.Println("значение по ptr после count = 100:", *ptr)
}
