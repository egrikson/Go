// Задача 2. Переставить указатель или поменять значение
//
// Главная ловушка темы: b = &a и *b = 5 выглядят похоже, а делают
// противоположное.
//
// Что сделать:
//  1. Завести x = 10 и y = 20.
//  2. Направить указатель p на x и записать через него 15.
//  3. ПЕРЕСТАВИТЬ p на y и записать через него 25.
//  4. Напечатать x и y одной строкой.
//  5. Завести второй указатель q на x.
//  6. Напечатать значение по p, значение по q и результат сравнения
//     p == q.
//
// Ожидаемый вывод:
//
//	x = 15, y = 25
//	p указывает на y: 25
//	q указывает на x: 15
//	p и q смотрят на одно? false
//
// Ограничения: переменные x и y по именам больше не трогать после
// объявления — всё только через указатели; p объявляется один раз, на
// шаге 3 ему присваивается новый адрес, а не создаётся новый указатель.
//
// Прежде чем запускать, ответь себе: почему x стал 15, а не 25? Ведь
// запись 25 шла через тот же самый p.
//
// Последняя строка сравнивает САМИ указатели, то есть адреса. Два
// указателя равны, когда смотрят в одно место, а не когда значения под
// ними совпадают.
//
// Запуск: go run ./block01/pointers/task2
package main

import "fmt"

func main() {
	x, y := 10, 20

	p := &x
	*p = 15

	p = &y
	*p = 25

	q := &x

	fmt.Printf("x = %d, y = %d\n", x, y)

	fmt.Printf("p указывает на y: %d\n", *p)
	fmt.Printf("q указывает на x: %d\n", *q)
	fmt.Println("p и q смотрят на одно?", p == q)
}
