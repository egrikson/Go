// Задача 2. Где лежит каждая руна
//
// Пройти по строке и для каждой руны напечатать четыре значения: байт, с
// которого она начинается, сам символ, номер в Unicode и сколько байтов
// она занимает.
//
// Вход: "aя⌘!"
//
// Ожидаемый вывод:
//
//	0 a U+0061 1
//	1 я U+044F 2
//	3 ⌘ U+2318 3
//	6 ! U+0021 1
//
// Ограничения: один цикл for range по строке, без пакетов кроме fmt.
//
// Запуск: go run ./block01/strings/task2
package main

import "fmt"

func main() {
	for i, r := range "aя⌘!" {
		fmt.Printf("%d %c %U %d\n", i, r, r, len(string(r)))
	}
}
