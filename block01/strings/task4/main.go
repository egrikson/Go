// Задача 4. Заглавные латинские буквы
//
// Написать функцию upperASCII(s string) string, которая делает заглавными
// только латинские буквы a–z. Всё остальное, включая кириллицу, остаётся
// как было. Напечатать результат для каждой строки из входа.
//
// Вход: "go и Go, привет!", "ПРИВЕТ", "x1y2"
//
// Ожидаемый вывод:
//
//	GO и GO, привет!
//	ПРИВЕТ
//	X1Y2
//
// Ограничения: работать через []byte, не через []rune. Исходная строка
// при этом не меняется. В блоке «Почему» объясни, почему байтовая обработка
// здесь не портит кириллицу, хотя в задаче 3 портила.
//
// Запуск: go run ./block01/strings/task4
package main

import "fmt"

func main() {
	list := []string{"go и Go, привет!", "ПРИВЕТ", "x1y2"}
	for _, v := range list {
		fmt.Println(upperASCII(v))
	}
}

func upperASCII(s string) string {
	b := []byte(s)
	for i, v := range b {
		if v >= 'a' && v <= 'z' {
			b[i] = v - 32
		}
	}
	return string(b)
}

