// Задача 4*. Функция меняет массив — или не меняет?
//
// Написать функцию double, которая принимает массив [5]int, удваивает
// каждый его элемент и печатает результат изнутри себя. В main:
// напечатать массив до вызова, вызвать double, напечатать массив после.
//
// Вход: [5]int{1, 2, 3, 4, 5}
//
// Ожидаемый вывод:
//
//	До вызова: [1 2 3 4 5]
//	Внутри функции: [2 4 6 8 10]
//	После вызова: [1 2 3 4 5]
//
// Прочитай ожидаемый вывод ещё раз. Функция честно удвоила все элементы
// и напечатала это. А в main массив остался прежним. Прежде чем писать
// код — объясни себе, почему так, и только потом запускай.
//
// Ограничения: никаких вторых массивов и копий руками — double получает
// обычный параметр типа [5]int; в main массив один, объявленный один раз.
//
// Подсказка: ты это уже проходил. В конспекте 2.10 записано, что
// присваивание массива копирует все элементы. Передача в функцию —
// тоже присваивание, просто параметру.
//
// Когда решишь — допиши комментарием в конце файла ответ на вопрос:
// что нужно изменить, чтобы функция реально меняла массив в main?
// Ответ на него — тема следующих двух разделов плана (указатели
// и слайсы), так что достаточно догадки своими словами.
//
// Запуск: go run ./block01/functions/task4
package main

import "fmt"

func main() {
	list := [5]int{1, 2, 3, 4, 5}
	fmt.Println("До вызова:", list)
	double(list)
	fmt.Println("После вызова:", list)
}

func double(data [5]int) {
	for i := 0; i < len(data); i++ {
		data[i] = data[i] * 2
	}
	fmt.Println("Внутри функции:", data)
}
