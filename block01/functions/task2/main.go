// Задача 2. Функция принимает массив
//
// Написать функцию printStats, которая принимает массив из 5 целых
// чисел и печатает сам массив, сумму его элементов и максимальный
// элемент. Вызвать её дважды с разными массивами.
//
// Вход: [5]int{4, 8, 15, 16, 23} и [5]int{7, 7, 7, 7, 7}
//
// Ожидаемый вывод:
//
//	Массив: [4 8 15 16 23]
//	Сумма: 66
//	Максимум: 23
//	Массив: [7 7 7 7 7]
//	Сумма: 35
//	Максимум: 7
//
// Ограничения: тип параметра — именно [5]int; сумму и максимум считать
// внутри функции через for range, максимум начинать с первого элемента,
// а не с нуля. Массивы передавать прямо в вызов, не заводя под них
// переменные в main.
//
// Запуск: go run ./block01/functions/task2
package main

import "fmt"

func main() {
	printStats([5]int{4, 8, 15, 16, 23})
	printStats([5]int{7, 7, 7, 7, 7})
}

func printStats(list [5]int) {
	var total int
	maxValue := list[0]

	for _, value := range list {
		total += value

		if value > maxValue {
			maxValue = value
		}
	}

	fmt.Println("Массив:", list)
	fmt.Println("Сумма:", total)
	fmt.Println("Максимум:", maxValue)
}
