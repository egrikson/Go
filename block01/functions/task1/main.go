// Задача 1. Функция с параметрами
//
// Написать функцию greet, которая принимает имя (string) и возраст (int)
// и печатает строку вида «Имя, N лет». Вызвать её три раза из main.
//
// Ожидаемый вывод:
//
//	Егор, 19 лет
//	Полина, 21 лет
//	Гость, 0 лет
//
// Ограничения: данные передавать только через параметры — никаких
// переменных уровня пакета и никаких значений, зашитых внутри самой
// функции. Функция ничего не возвращает (возврат значений — следующий
// шаг урока), она только печатает.
//
// Запуск: go run ./block01/functions/task1
package main

import "fmt"

func great(name string, age int) {
	fmt.Printf("%s, %d лет\n", name, age)
}

func main() {
	great("Егор", 19)
	great("Полина", 21)
	great("Гость", 0)
}
