// Задача 6*. Когда append портит соседа, а когда нет
//
// Выполни ровно эти шаги:
//
//	s := []int{1, 2, 3, 4, 5}
//	head := s[:2]
//	head = append(head, 99)
//	// печать head и s
//	tail := s[3:]
//	s = append(s, 6)
//	s[3] = 0
//	// печать s и tail
//
// СНАЧАЛА впиши в блок «Предсказание» все строки вывода, потом запускай.
//
// Формат вывода (значения — твоё предсказание):
//
//	head: [...]
//	s: [...]
//	после append к s и s[3] = 0:
//	s: [...]
//	tail: [...]
//
// В блоке «Почему» объясни две вещи: почему append к head изменил s, и
// почему s[3] = 0 после append к s НЕ изменил tail. Опирайся на len и cap
// каждого среза в момент append.
//
// Запуск: go run ./block01/slices-append/task6
package main

import "fmt"

func main() {
	s := []int{1, 2, 3, 4, 5}
	head := s[:2]
	head = append(head, 99)

	fmt.Println("head:", head)
	fmt.Println("s:", s)
	tail := s[3:]
	s = append(s, 6)
	s[3] = 0

	fmt.Println("после append к s и s[3] = 0:")
	fmt.Println("s:", s)
	fmt.Println("tail:", tail)
}

// --- Предсказание (заполнить ДО запуска) ---
//
// head: 1 2 99
// s: 1 2 99 4 5
// после append к s и s[3] = 0:
// s: 1 2 99 0 5 6
// tail: 4 5

// --- Почему ---
//
// Массив под s: [1][2][3][4][5], cap(s) = 5.
//
// 1. head := s[:2] -> [1 2], len 2, cap 5. Массив общий с s.
//
// 2. append(head, 99): len 2 < cap 5, место есть. Нового массива нет,
//    99 пишется в тот же массив на позицию len(head) = 2, то есть в s[2].
//    Тройка затёрта, поэтому s = [1 2 99 4 5].
//
// 3. tail := s[3:] -> [4 5], len 2, cap 2. Смотрит в тот же массив,
//    что и s, начиная с индекса 3.
//
// 4. append(s, 6): len 5 == cap 5, места нет. append создаёт новый
//    массив побольше, копирует туда [1 2 99 4 5], дописывает 6.
//    s теперь смотрит в новый массив, tail остался в старом.
//
// 5. s[3] = 0 меняет новый массив. В старом массиве, куда смотрит tail,
//    по-прежнему 4, поэтому tail = [4 5].
//
// Итог: если при append len < cap, он пишет в общий массив и может
// испортить соседний срез. Если len == cap, он уезжает в новый массив,
// и связь с соседями рвётся.
