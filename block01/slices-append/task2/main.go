// Задача 2. Два append от одного среза
//
// От одного и того же среза base делаются два append:
//
//	base := make([]int, 3, 5)
//	a := append(base, 1)
//	b := append(base, 2)
//
// Затем то же самое, но base создан без запаса: make([]int, 3), и
// результаты называются c и d.
//
// СНАЧАЛА впиши в блок «Предсказание» обе строки вывода, потом запускай.
// Если ошибся — не исправляй предсказание, а допиши, где именно.
//
// Формат вывода (значения — твоё предсказание):
//
//	cap 5: a=[...] b=[...] base=[...]
//	cap 3: c=[...] d=[...] base=[...]
//
// В блоке «Почему» объясни, чем отличаются два случая.
//
// Запуск: go run ./block01/slices-append/task2
package main

import "fmt"

func main() {
	base := make([]int, 3, 5)
	a := append(base, 1)
	b := append(base, 2)
	fmt.Printf("cap %d: a=%v b=%v base=%v\n", cap(base), a, b, base)

	base = make([]int, 3)
	c := append(base, 1)
	d := append(base, 2)
	fmt.Printf("cap %d: c=%v d=%v base=%v\n", cap(base), c, d, base)
}

// --- Предсказание (заполнить ДО запуска) ---
//
// cap 5:a=[0 0 0 2] b=[0 0 0 2] base=[0 0 0]
// cap 3:c=[0 0 0 1] d=[0 0 0 2] base=[0 0 0]

// --- Почему ---
//
// append(base, x) кладёт x в ячейку с индексом len(base), если она в
// пределах cap. Что там уже кто-то записал, append не знает: срез хранит
// только начало, длину и ёмкость.
//
// cap 5: у base len=3, cap=5 — место есть, новый массив не создаётся.
// Оба append пишут в ОДНУ и ту же ячейку 3 общего массива: сначала 1,
// потом 2 затирает её. a и b смотрят в этот массив, поэтому оба видят 2.
// Сам base не меняется — его длина по-прежнему 3.
//
// cap 3: места нет, и каждый append создаёт СВОЙ новый массив и копирует
// туда 0 0 0. У c и d разные массивы, поэтому они друг другу не мешают.
//
// Правило: cap хватает — append пишет в старый массив, и это видят все
// срезы на него; cap не хватает — новый массив, связь обрывается.
// (Если бы второй вызов был append(a, 2), двойка легла бы в ячейку 4.)
