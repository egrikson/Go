// Задача 2. Деление, которое может не получиться
//
// Написать функцию divide(a, b int) (int, bool): возвращает частное от
// целочисленного деления и признак успеха. При делении на ноль вернуть
// 0 и false — программа НЕ должна падать.
//
// Вызвать дважды: divide(10, 3) и divide(10, 0).
//
// Ожидаемый вывод:
//
//	10 / 3 = 3
//	10 / 0: деление на ноль
//
// Ограничения: внутри divide нет ни одного fmt; решение о том, что
// печатать, принимает main по второму возвращаемому значению.
// Результат проверять краткой конструкцией if — той самой из
// block01/if-short: if q, ok := divide(10, 3); ok { ... }
//
// Зачем это нужно. Пара «значение + признак» — базовая идиома Go.
// Функция не умеет «вернуть ничего» или «бросить исключение», поэтому
// вторым значением она честно сообщает, получилось или нет. Позже
// вместо bool там будет error, но механика останется той же.
//
// Проверь себя: если убрать проверку на ноль, программа упадёт с
// паникой «integer divide by zero». Попробуй — полезно увидеть, от
// чего именно ты защищаешься.
//
// Запуск: go run ./block01/functions-multi/task2
package main

import "fmt"

func main() {
	if q, ok := divide(10, 3); ok {
		fmt.Println("10 / 3 =", q)
	} else {
		fmt.Println("10 / 3: деление на ноль")
	}
	if q, ok := divide(10, 0); ok {
		fmt.Println("10 / 0 =", q)
	} else {
		fmt.Println("10 / 0: деление на ноль")
	}
}

func divide(a, b int) (int, bool) {
	if b == 0 {
		return 0, false
	}

	return a / b, true
}
