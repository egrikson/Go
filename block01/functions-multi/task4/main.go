// Задача 4*. Секунды в часы, минуты и секунды
//
// Перевести 3725 секунд в формат «часы, минуты, секунды».
//
// Ожидаемый вывод:
//
//	3725 сек = 1 ч 2 мин 5 сек
//
// Ограничения: написать ОДНУ вспомогательную функцию
//
//	divmod(a, b int) (int, int)
//
// возвращающую частное и остаток, и вызвать её ДВА раза. В main не
// должно быть ни одного оператора / или % — вся арифметика деления
// живёт внутри divmod.
//
// В этом и смысл задачи. Деление с остатком — одна операция, у которой
// два результата, и в Go её можно оформить именно так. Первый вызов
// отделяет часы от остатка, второй делит остаток на минуты и секунды:
// результат первого вызова становится входом второго.
//
// Проверь себя: 3725 = 1 час (3600) + 2 минуты (120) + 5 секунд.
// Подставь 59 — должно выйти 0 ч 0 мин 59 сек. Подставь 7200 —
// 2 ч 0 мин 0 сек.
//
// Запуск: go run ./block01/functions-multi/task4
package main

import "fmt"

func main() {
	const total int = 3725

	hours, rest := divmod(total, 3600)
	minutes, seconds := divmod(rest, 60)

	fmt.Printf("%d сек = %d ч %d мин %d сек\n", total, hours, minutes, seconds)
}

func divmod(a, b int) (int, int) {
	return a / b, a % b
}
