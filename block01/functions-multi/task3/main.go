// Задача 3. Три значения и пустой идентификатор
//
// Написать функцию stats(numbers [5]int) (int, int, int), возвращающую
// сумму, минимум и максимум — за один проход по массиву.
//
// Вызвать её дважды:
//  1. взять все три значения и напечатать одной строкой;
//  2. взять ТОЛЬКО максимум, остальные два отбросить через _.
//
// Вход: [5]int{12, 45, 7, 23, 38}
//
// Ожидаемый вывод:
//
//	Сумма: 125, минимум: 7, максимум: 45
//	Только максимум: 45
//
// Ограничения: один цикл внутри stats, не три; первая строка печатается
// одним вызовом Printf, а не тремя Println; во втором вызове ненужные
// значения обязательно через _ — заводить переменные и не использовать
// их нельзя, это ошибка компиляции.
//
// Запуск: go run ./block01/functions-multi/task3
//
// ┌─────────────────────────────────────────────────────────────────┐
// │ НЕ ДОДЕЛАНО — решение работает, но условию соответствует не всё │
// └─────────────────────────────────────────────────────────────────┘
//
//  1. Нет второго вызова stats с пустым идентификатором.
//     Условие просило вызвать функцию ДВАЖДЫ и во второй раз взять
//     только максимум: _, _, maxValue := stats(data). Сейчас вместо
//     этого переиспользуется maxData из первого вызова, то есть
//     упражнение на "_" не отработано.
//
//  2. maxValue внутри stats стартует с нуля, а не с numbers[0].
//     На этих данных работает случайно: все числа положительные, и
//     45 больше нуля. Подставь массив из отрицательных — функция
//     вернёт 0, которого в массиве нет. minValue при этом взят
//     правильно, с первого элемента.
//
//  3. Порядок возврата разошёлся с условием.
//     Условие: (сумма, минимум, максимум). В коде: (sum, maxValue,
//     minValue). Сейчас не ломается, потому что main принимает в том
//     же порядке, но из сигнатуры (int, int, int) понять, где что,
//     невозможно — ни компилятор, ни имя функции не подсказывают.
//
// Третий пункт — лучшая иллюстрация к теме "именованные возвращаемые
// значения": с ними сигнатура превращается в
//
//	func stats(numbers [5]int) (sum, min, max int)
//
// и вопрос о порядке отпадает сам. Вернуться сюда после этой темы.
package main

import "fmt"

func main() {
	data := [5]int{12, 45, 7, 23, 38}
	var sumData, maxData, minData = stats(data)
	fmt.Printf("Сумма: %d, минимум: %d, максимум: %d\n", sumData, minData, maxData)
	fmt.Println("Только максимум:", maxData)
}

func stats(numbers [5]int) (int, int, int) {
	var sum int
	var maxValue int
	minValue := numbers[0]

	for _, value := range numbers {
		sum += value
		if value > maxValue {
			maxValue = value
		}
		if value < minValue {
			minValue = value
		}
	}

	return sum, maxValue, minValue
}
