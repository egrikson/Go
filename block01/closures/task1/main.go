// Задача 1. Функция в переменной
//
// Разминка на то, что функция — это значение.
//
// Что сделать:
//  1. Объявить обычную функцию triple(x int) int — умножает на 3.
//  2. В main положить ЕЁ САМУ в переменную f (без скобок!) и вызвать
//     f(14).
//  3. Завести переменную half с анонимной функцией, которая делит
//     пополам, и вызвать half(14).
//  4. Напечатать тип переменной f глаголом %T.
//  5. Последней строкой объявить анонимную функцию с параметром
//     msg string, печатающую «вызвана на месте: <msg>», и вызвать её
//     прямо на месте, не сохраняя в переменную.
//
// Ожидаемый вывод:
//
//	f(14) = 42
//	half(14) = 7
//	тип f: func(int) int
//	вызвана на месте: конец разминки
//
// Ограничения: triple объявлена обычным способом, half — анонимная;
// пятая функция нигде не сохраняется.
//
// Если написать f := triple(14), в переменной окажется число 42, а не
// функция. Скобки — это операция вызова. Разницу стоит почувствовать
// руками: попробуй оба варианта и посмотри, что скажет %T.
//
// Запуск: go run ./block01/closures/task1
package main

import "fmt"

func main() {
	f := triple
	half := func(x int) int { return x / 2 }

	fmt.Printf("f(14) = %d\n", f(14))
	fmt.Printf("half(14) = %d\n", half(14))
	fmt.Printf("тип f: %T\n", f)

	func(msg string) {
		fmt.Println("вызвана на месте:", msg)
	}("конец разминки")
}

func triple(x int) int {
	return x * 3
}
