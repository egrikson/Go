// Задача 3. Два независимых счёта
//
// Написать функцию, возвращающую замыкание:
//
//	func account(balance int) func(int) int
//
// Она получает стартовый баланс и возвращает функцию, которая принимает
// изменение суммы (плюс — приход, минус — расход), применяет его и
// возвращает новый баланс. Баланс живёт внутри замыкания: снаружи к
// нему не подобраться и случайно не испортить.
//
// В main открыть ДВА счёта: first со стартом 100 и second со стартом 0.
// Провести операции в таком порядке:
//
//	first(50), first(-30), second(7), first(0), second(3)
//
// Ожидаемый вывод:
//
//	счёт 1: 150
//	счёт 1: 120
//	счёт 2: 7
//	счёт 1: 120
//	счёт 2: 10
//
// Ограничения: никаких переменных на уровне пакета; account вызывается
// ровно дважды; внутри возвращаемой функции нельзя заводить новую
// переменную под баланс — менять надо ту, что пришла параметром.
//
// Главное в задаче — четвёртая строка вывода. После операций со вторым
// счётом первый показывает 120, а не 127: у каждого вызова account свой
// собственный balance. Один вызов — один комплект переменных.
//
// Проверь себя: что напечатает пятая строка, если поменять местами
// second(7) и second(3)? Ответь, не запуская.
//
// Запуск: go run ./block01/closures/task3
package main

import "fmt"

func main() {
	first := account(100)
	second := account(0)

	fmt.Printf("счёт 1: %d\n", first(50))
	fmt.Printf("счёт 1: %d\n", first(-30))
	fmt.Printf("счёт 2: %d\n", second(7))
	fmt.Printf("счёт 1: %d\n", first(0))
	fmt.Printf("счёт 2: %d\n", second(3))

}

func account(balance int) func(int) int {
	return func(x int) int {
		balance += x
		return balance
	}
}
