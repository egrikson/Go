// Задача 2. Функция как параметр
//
// Написать функцию, которая обходит массив, но не знает, что делать с
// элементом — это ей приносят снаружи:
//
//	func apply(nums [5]int, f func(int) int) [5]int
//
// Она возвращает НОВЫЙ массив, где к каждому элементу применена f.
// Исходный массив не меняется.
//
// Вход: [5]int{-3, 1, 4, -1, 5}
//
// Вызвать apply три раза:
//  1. с функцией triple из задачи 1 (объявить её заново);
//  2. с анонимной функцией «в квадрат», записанной ПРЯМО В АРГУМЕНТЕ;
//  3. с анонимной функцией, заменяющей отрицательные числа на 0, — тоже
//     прямо в аргументе.
//
// Ожидаемый вывод:
//
//	исходный:    [-3 1 4 -1 5]
//	утроенные:   [-9 3 12 -3 15]
//	квадраты:    [9 1 16 1 25]
//	без минусов: [0 1 4 0 5]
//
// Ограничения: один цикл внутри apply; массивы печатать через %v одним
// Printf на строку; отступы в выводе повторить точно — это обычные
// пробелы в строке формата.
//
// Третья функция занимает несколько строк вместе с if — так тоже можно,
// анонимная функция не обязана быть однострочной.
//
// Обрати внимание, что исходный массив остался прежним, хотя мы его
// передавали в apply три раза. Массив копируется при передаче — это
// ты уже проверял в block01/functions/task4.
//
// Запуск: go run ./block01/closures/task2
package main

import "fmt"

func main() {
	data := [5]int{-3, 1, 4, -1, 5}
	fmt.Printf("%-13s%v\n", "исходный:", data)
	fmt.Printf("%-13s%v\n", "утроенные:", apply(data, triple))
	fmt.Printf("%-13s%v\n", "квадраты:", apply(data, func(x int) int { return x * x }))
	fmt.Printf("%-13s%v\n", "без минусов:", apply(data, func(x int) int {
		if x < 0 {
			return 0
		}
		return x
	}))
}

func triple(x int) int {
	return x * 3
}

func apply(nums [5]int, f func(int) int) [5]int {
	var out [5]int
	for i, v := range nums {
		out[i] = f(v)
	}
	return out
}
