// Задача 4*. Трассировка вложенных вызовов
//
// Самая полезная задача набора: здесь замыкание работает вместе с
// defer, и понадобится всё, что ты знаешь про обоих.
//
// Написать функцию:
//
//	func tracer(name string) func()
//
// При вызове она сразу печатает «вход: <name>» и возвращает функцию,
// которая печатает «выход: <name>».
//
// Написать две функции, вложенные друг в друга:
//   - outer() — вызывает inner();
//   - inner() — печатает «работаю внутри».
//
// В каждой из них ПЕРВОЙ строкой поставить трассировку — ровно одну
// строку на функцию. В main вызвать только outer().
//
// Ожидаемый вывод:
//
//	вход: outer
//	вход: inner
//	работаю внутри
//	выход: inner
//	выход: outer
//
// Ограничения: ровно один defer в outer и один в inner; tracer
// вызывается только в этих двух строках; никаких глобальных
// переменных и счётчиков вложенности.
//
// Подсказка на один шаг, не дальше: в строке с defer тебе нужны ДВЕ
// пары скобок, и они делают разные вещи в разное время. Первая
// вычисляется сразу, вторая откладывается.
//
// Почему вывод выходит симметричным, «ёлочкой» — разберись сам. Ответ
// собирается из двух уже известных правил: аргументы defer вычисляются
// немедленно, а отложенные вызовы срабатывают в порядке LIFO при
// выходе из функции.
//
// Этот приём — не учебный пример: так в реальном коде смотрят, куда
// программа заходит и в каком порядке выходит.
//
// Запуск: go run ./block01/closures/task4
package main

import "fmt"

func main() {
	outer()
}

func tracer(name string) func() {
	fmt.Printf("вход: %s\n", name)
	return func() {
		fmt.Printf("выход: %s\n", name)
	}
}

func outer() {
	defer tracer("outer")()
	inner()
}

func inner() {
	defer tracer("inner")()
	fmt.Println("работаю внутри")
}
