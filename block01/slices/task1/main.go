// Задача 1. Три части суток
//
// Из массива температур сделать три среза: утро — элементы 0–2,
// день — 3–5, вечер — 5–7 (день и вечер пересекаются на элементе 5).
// Написать функцию sum(s []int) int и посчитать сумму каждой части.
//
// Вход: temps := [8]int{-3, 0, 4, 7, 12, 9, 5, -1}
//
// Ожидаемый вывод:
//
//	Утро: [-3 0 4], сумма 1
//	День: [7 12 9], сумма 28
//	Вечер: [9 5 -1], сумма 13
//
// Ограничения: одна функция sum на все три среза; в каждом срезе оба
// индекса указывать явно. Не использовать литералы []int{...}, make,
// append, len для срезов и запись a[:n] — это ещё не пройдено.
//
// Запуск: go run ./block01/slices/task1
package main

import "fmt"

func main() {
	temps := [8]int{-3, 0, 4, 7, 12, 9, 5, -1}

	fmt.Printf("Утро: %v, сумма %d\n", temps[0:3], sum(temps[0:3]))
	fmt.Printf("День: %v, сумма %d\n", temps[3:6], sum(temps[3:6]))
	fmt.Printf("Вечер: %v, сумма %d\n", temps[5:8], sum(temps[5:8]))
}

func sum(s []int) int {
	sum := 0
	for _, value := range s {
		sum += value
	}
	return sum
}
