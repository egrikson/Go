// Задача 2. Чистка середины
//
// Написать функцию zeroNegatives(s []int) int: заменяет отрицательные
// элементы среза нулями и возвращает количество замен. Применить её
// только к элементам массива с индексами 2–7, затем напечатать весь массив.
//
// Вход: data := [10]int{5, -2, 8, -7, -1, 3, -4, 6, -9, 2}
//
// Ожидаемый вывод:
//
//	Заменено: 3
//	Массив: [5 -2 8 0 0 3 0 6 -9 2]
//
// Ограничения: функция не принимает указатель и не возвращает срез;
// main печатает сам массив data, а не срез.
//
// Отдельно — в блоке «Почему» в конце файла объяснить, почему массив
// изменился, хотя в block01/functions/task4 массив, переданный в
// функцию, не менялся.
//
// Запуск: go run ./block01/slices/task2
package main

import "fmt"

func main() {
	data := [10]int{5, -2, 8, -7, -1, 3, -4, 6, -9, 2}
	replaced := zeroNegatives(data[2:8])

	fmt.Printf("Заменено: %d\n", replaced)
	fmt.Printf("Массив: %v\n", data)
}

func zeroNegatives(s []int) int {
	count := 0

	for i, v := range s {
		if v < 0 {
			s[i] = 0
			count++
		}
	}
	return count
}

// --- Почему ---
//[10]int - хранит в себе копии всех десяти чисел, а []int - хранит адресс начала участка памяти. В функцию приходит копия описателя, а она ведёт на массив.
