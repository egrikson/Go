// Задача 4*. Вернуть указатель наружу
//
// Две функции, обе принимают *[5]int, но возвращают разное:
//
//	func maxPtr(arr *[5]int) *int      — указатель НА максимальный элемент
//	func clone(arr *[5]int) *[5]int    — указатель на НЕЗАВИСИМУЮ копию
//
// maxPtr ищет максимум и возвращает указатель внутрь переданного
// массива. clone создаёт новый массив через new и переписывает в него
// элементы по одному.
//
// В main:
//  1. завести nums = [5]int{12, 45, 7, 23, 38};
//  2. сделать копию через clone;
//  3. получить указатель на максимум через maxPtr и напечатать его
//     значение;
//  4. записать 0 по этому указателю;
//  5. напечатать оригинал и копию.
//
// Ожидаемый вывод:
//
//	максимум: 45
//	оригинал: [12 0 7 23 38]
//	копия:    [12 45 7 23 38]
//
// Ограничения: в clone массив создать именно через new; копировать
// циклом поэлементно; в main ни одного обращения к nums по индексу.
//
// Последние две строки — суть задачи. Один указатель смотрит ВНУТРЬ
// чужого массива, поэтому запись через него видна снаружи. Второй
// указывает на отдельный массив, который живёт своей жизнью.
//
// И обрати внимание, что массив, созданный внутри clone, прекрасно
// существует после выхода из функции. В C так вернуть локальную
// переменную нельзя, в Go можно: компилятор сам решает, где её
// разместить.
//
// Запуск: go run ./block01/pointers-func/task4
package main

import "fmt"

func main() {
	nums := [5]int{12, 45, 7, 23, 38}
	numsClone := *clone(&nums)
	numsMax := maxPtr(&nums)
	fmt.Println("максимум:", *numsMax)
	*numsMax = 0
	fmt.Println("оригинал:", nums)
	fmt.Println("копия:", numsClone)

}

func maxPtr(arr *[5]int) *int {
	maxArr := &arr[0]
	for i := range arr {
		if *maxArr < arr[i] {
			maxArr = &arr[i]
		}
	}
	return maxArr
}

func clone(arr *[5]int) *[5]int {
	cloneArr := new([5]int)
	for i := range arr {
		cloneArr[i] = arr[i]
	}
	return cloneArr
}
