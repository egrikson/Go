// Задача 1. Копия против оригинала
//
// Написать две функции, которые делают «одно и то же» — удваивают
// число, — и убедиться, что результат у них разный:
//
//	func double(x int)
//	func doublePtr(x *int)
//
// Обе ничего не возвращают. Первая принимает число, вторая — указатель
// на число.
//
// В main завести count = 7, напечатать его, вызвать double, напечатать
// снова, вызвать doublePtr, напечатать ещё раз.
//
// Ожидаемый вывод:
//
//	до:              7
//	после double:    7
//	после doublePtr: 14
//
// Ограничения: обе функции без return; выравнивание подписей — через
// %-17s или вручную, но столбец должен сойтись.
//
// Вторая строка — весь смысл задачи. double честно удвоила число,
// просто это было не то число: функция получила копию, удвоила копию,
// и копия исчезла вместе с функцией.
//
// Запуск: go run ./block01/pointers-func/task1
package main

import "fmt"

func main() {
	count := 7
	fmt.Printf("%-17s%d\n", "до:", count)

	double(count)
	fmt.Printf("%-17s%d\n", "после double:", count)

	doublePtr(&count)
	fmt.Printf("%-17s%d\n", "после doublePtr:", count)

}

func double(x int) {
	x *= 2
}

func doublePtr(x *int) {
	*x *= 2
}
