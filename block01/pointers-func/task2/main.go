// Задача 2. Поменять местами
//
// Написать функцию swap(a, b *int), которая меняет местами значения
// двух переменных вызывающей стороны.
//
// В main завести a = 1, b = 2, напечатать, вызвать swap, напечатать.
//
// Ожидаемый вывод:
//
//	до:    a = 1, b = 2
//	после: a = 2, b = 1
//
// Ограничения: swap ничего не возвращает; внутри неё временную
// переменную заводить НЕ надо — хватит множественного присваивания,
// которое ты видел в генераторе Фибоначчи (a, b = b, a+b).
//
// Подумай заодно, почему функция swap(a, b int) без указателей была бы
// бесполезна, хотя скомпилировалась бы без единой ошибки.
//
// Запуск: go run ./block01/pointers-func/task2
package main

import "fmt"

func main() {
	a, b := 1, 2
	fmt.Printf("до:    a = %d, b = %d\n", a, b)
	swap(&a, &b)
	fmt.Printf("после: a = %d, b = %d\n", a, b)
}

func swap(a, b *int) {
	*a, *b = *b, *a
}
