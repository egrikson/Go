// Задача 3. Массив: 40 байт против 8
//
// Вернуться к тому, обо что ты споткнулся в closures/task2, и увидеть
// обе стороны рядом.
//
// Написать две функции, умножающие каждый элемент массива на k:
//
//	func scaleValue(arr [5]int, k int)
//	func scalePtr(arr *[5]int, k int)
//
// Обе ничего не возвращают, обе меняют arr внутри себя.
//
// В main: массив [5]int{1, 2, 3, 4, 5}, напечатать; вызвать
// scaleValue с k = 3, напечатать; вызвать scalePtr с k = 3,
// напечатать.
//
// Ожидаемый вывод:
//
//	было:             [1 2 3 4 5]
//	после scaleValue: [1 2 3 4 5]
//	после scalePtr:   [3 6 9 12 15]
//
// Ограничения: в обеих функциях цикл через for i := range arr; внутри
// scalePtr писать (*arr)[i] НЕ нужно — проверь, что arr[i] работает
// само, и объясни себе почему.
//
// Что тут стоит заметить. Код внутри двух функций почти одинаковый,
// отличается только тип параметра — и этого хватает, чтобы одна
// работала вхолостую, а вторая меняла оригинал.
//
// И про цену: [5]int весит 40 байт, указатель на него — 8, независимо
// от длины массива. На пяти числах это неважно, на десяти тысячах
// scaleValue копировала бы 80 КБ на каждый вызов.
//
// Запуск: go run ./block01/pointers-func/task3
package main

import "fmt"

func main() {
	data := [5]int{1, 2, 3, 4, 5}
	fmt.Println("было:", data)
	scaleValue(data, 3)
	fmt.Println("после scaleValue:", data)
	scalePtr(&data, 3)
	fmt.Println("после scalePtr:", data)
}

func scaleValue(arr [5]int, k int) {
	for i := range arr {
		arr[i] = arr[i] * k
	}
}

func scalePtr(arr *[5]int, k int) {
	for i := range arr {
		arr[i] = arr[i] * k
	}

}
