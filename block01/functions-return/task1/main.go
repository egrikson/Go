// Задача 1. Функция возвращает результат
//
// Написать две функции для прямоугольника со сторонами 7 и 4:
//
//	area(w, h int) int      — площадь
//	perimeter(w, h int) int — периметр
//
// Обе ДОЛЖНЫ возвращать число, а не печатать его. Печатает main.
//
// Ожидаемый вывод:
//
//	Площадь: 28
//	Периметр: 22
//
// Ограничения: внутри area и perimeter не должно быть ни одного вызова
// fmt — они только считают. Это главное отличие от прошлого набора
// задач, где функции печатали сами.
//
// Заодно: если у параметров одинаковый тип, тип пишется один раз для
// последнего — func area(w, h int) int, а не (w int, h int) int.
//
// Запуск: go run ./block01/functions-return/task1
package main

import "fmt"

func main() {
	fmt.Println("Площадь:", area(7, 4))
	fmt.Println("Периметр:", perimeter(7, 4))
}

func area(w, h int) int {
	return w * h
}

func perimeter(w, h int) int {
	return (w + h) * 2
}
