// Задача 4*. Массив задом наперёд, не идя назад
//
// Написать функцию reverse(numbers [5]int), которая печатает элементы
// массива в ОБРАТНОМ порядке. Ограничение жёсткое: единственный цикл в
// функции идёт от начала массива к концу (for range или i++), индекс
// нигде не убывает, второго массива и никаких переменных-накопителей
// нет. Разворот должен получиться сам.
//
// Перед разворотом функция печатает подпись «в обратном порядке: ».
//
// В main: напечатать исходный массив [5]int{10, 20, 30, 40, 50} в
// прямом порядке, затем вызвать reverse.
//
// Ожидаемый вывод:
//
//	исходный массив: 10 20 30 40 50
//	в обратном порядке: 50 40 30 20 10
//
// Ограничения: печать элементов через fmt.Print(v, " ") — так между
// числами будет ровно один пробел; перевод строки после каждой из двух
// строк ставить в main.
//
// Подсказка на один шаг, не дальше: подумай, в каком порядке выполнятся
// пять отложенных вызовов, если объявить их в цикле.
//
// И подумай заодно, почему подпись «в обратном порядке: » печатается
// раньше чисел, хотя в коде функции она стоит после цикла.
//
// Запуск: go run ./block01/defer/task4
package main

import "fmt"

func main() {
	data := [5]int{10, 20, 30, 40, 50}

	fmt.Print("исходный массив: ")
	for _, value := range data {
		fmt.Print(value, " ")
	}

	fmt.Println()

	reverse(data)
	fmt.Println()
}

func reverse(numbers [5]int) {
	for i := 0; i < len(numbers); i++ {
		defer fmt.Print(numbers[i], " ")
	}
	fmt.Print("в обратном порядке: ")
}
