// Задача 2. Что именно видит defer
//
// Написать функцию report() без параметров и без возврата:
//  1. завести переменную total со значением 0;
//  2. сразу за ней — defer, печатающий «итог по версии defer: <total>»;
//  3. цикл i от 1 до 3: прибавить i к total и объявить ещё один defer,
//     печатающий «шаг <i>»;
//  4. после цикла напечатать «итог на самом деле: <total>».
//
// СНАЧАЛА выпиши на бумаге, что напечатается и в каком порядке.
// Только потом запускай и сравнивай. Ожидаемый вывод ниже — не
// подглядывай, пока не сделал прогноз.
//
// Ожидаемый вывод:
//
//	итог на самом деле: 6
//	шаг 3
//	шаг 2
//	шаг 1
//	итог по версии defer: 0
//
// Ограничения: ровно три строки с defer в тексте функции (одна снаружи
// цикла, одна внутри); total после цикла не трогать.
//
// В этом выводе спрятаны оба правила темы. Порядок «3, 2, 1» — это
// LIFO. А «итог по версии defer: 0» — это момент вычисления аргументов:
// значение total взяли в ту секунду, когда выполнилась строка с defer,
// а не тогда, когда отложенный вызов наконец сработал.
//
// Запуск: go run ./block01/defer/task2
package main

import "fmt"

func main() {
	report()
}

func report() {
	total := 0
	defer fmt.Printf("итог по версии defer: %d\n", total)
	for i := 1; i <= 3; i++ {
		total += i
		defer fmt.Printf("шаг %d\n", i)
	}
	fmt.Printf("итог на самом деле: %d\n", total)
}
