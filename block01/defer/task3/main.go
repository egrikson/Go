// Задача 3. Много выходов — один defer
//
// Написать функцию с именованным возвратом:
//
//	func check(n int) (verdict string)
//
// Она классифицирует число и возвращает одно из четырёх слов:
// "отрицательное", "ноль", "чётное", "нечётное" — каждое своим
// отдельным return. Первой строкой функции поставить defer, который
// печатает «  (проверка <n> завершена)» с двумя пробелами в начале.
//
// В main перебрать через for range массив [4]int{-5, 0, 8, 7} и для
// каждого числа напечатать «<n>: <verdict>».
//
// Ожидаемый вывод:
//
//	  (проверка -5 завершена)
//	-5: отрицательное
//	  (проверка 0 завершена)
//	0: ноль
//	  (проверка 8 завершена)
//	8: чётное
//	  (проверка 7 завершена)
//	7: нечётное
//
// Ограничения: четыре разных return внутри check, ни одного else;
// ровно один defer; в main один Printf на строку.
//
// Два момента, ради которых задача написана.
//
// Первый: выходов из функции четыре, а строку про завершение ты написал
// один раз. Без defer её пришлось бы дублировать перед каждым return —
// и рано или поздно один из них забыли бы. Именно поэтому defer ставят
// сразу после открытия ресурса, а не в конце функции.
//
// Второй: посмотри, почему строка про проверку идёт ПЕРЕД строкой с
// результатом, хотя в main вызов check стоит внутри Printf. Разберись
// сам, в каком порядке тут всё происходит.
//
// Запуск: go run ./block01/defer/task3
package main

import "fmt"

func main() {
	data := [4]int{-5, 0, 8, 7}

	for _, value := range data {
		fmt.Printf("%d: %s\n", value, check(value))
	}
}

func check(n int) (verdict string) {
	defer fmt.Printf("  (проверка %d завершена)\n", n)

	if n < 0 {
		return "отрицательное"
	}
	if n == 0 {
		return "ноль"
	}
	if n%2 == 0 {
		return "чётное"
	}

	return "нечётное"
}
