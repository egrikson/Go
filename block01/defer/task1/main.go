// Задача 1. Открыл — закрой
//
// Написать функцию process(name string), которая:
//   - ПЕРВОЙ строкой планирует через defer печать «готово: <name>»;
//   - следом печатает «обрабатываю: <name>».
//
// Вызвать её для "отчёт", затем для "счёт".
//
// Ожидаемый вывод:
//
//	обрабатываю: отчёт
//	готово: отчёт
//	обрабатываю: счёт
//	готово: счёт
//
// Ограничения: defer стоит первой строкой функции; печатать «готово»
// обычным вызовом в конце нельзя — в этом вся задача.
//
// Обрати внимание на порядок строк в выводе. Ты написал defer первым,
// а напечатался он вторым — и так для каждого вызова отдельно.
//
// Запуск: go run ./block01/defer/task1
package main

import "fmt"

func main() {
	process("отчёт")
	process("счёт")
}

func process(name string) {
	defer fmt.Printf("готово: %s\n", name)

	fmt.Printf("обрабатываю: %s\n", name)
}
