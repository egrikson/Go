// Задача 3. Простое или составное
//
// Дано var n int = 91. Определить, простое число или составное. Если
// составное — назвать наименьший делитель. Заодно посчитать, сколько
// делителей было проверено до ответа.
//
// Ожидаемый вывод:
//
//	91 — составное, наименьший делитель 7
//	Проверено делителей: 6
//
// Ограничения: делители перебирать начиная с 2; остаток от деления
// вычислять только в краткой инструкции if; как только делитель найден —
// выйти из цикла через break, лишние проверки не делать.
//
// Проверь себя: подставь n = 97 (простое) — программа обязана сказать
// «97 — простое» и не соврать про делитель. Подставь n = 4 — ответ
// «наименьший делитель 2, проверено делителей: 1».
//
// Запуск: go run ./block01/if-short/task3
package main

import "fmt"

func main() {
	var n int = 91

	divisor := 0
	checked := 0

	for i := 2; i < n; i++ {
		checked++

		if rem := n % i; rem == 0 {
			divisor = i
			break
		}
	}

	if divisor == 0 {
		fmt.Printf("%d — простое\n", n)
	} else {
		fmt.Printf("%d — составное, наименьший делитель %d\n", n, divisor)
	}

	fmt.Println("Проверено делителей:", checked)
}
