// Задача 2. Отклонение от нормы
//
// Даны var temps = [5]int{18, 25, 30, 12, 22} и const norm int = 22.
// Для каждой температуры вывести, насколько она отличается от нормы:
// выше, ниже или ровно норма. Величину отклонения печатать
// положительным числом в обоих случаях.
//
// Ожидаемый вывод:
//
//	18: ниже нормы на 4
//	25: выше нормы на 3
//	30: выше нормы на 8
//	12: ниже нормы на 10
//	22: норма
//
// Ограничения: перебор через for range; отклонение вычисляется один раз
// в краткой инструкции if и используется во всех трёх ветках цепочки
// if / else if / else — повторно считать t - norm нельзя. Знак минус
// убирать не через отдельную переменную, а прямо при выводе.
//
// Запуск: go run ./block01/if-short/task2
package main

import "fmt"

func main() {
	var temps = [5]int{18, 25, 30, 12, 22}
	const norm int = 22

	for _, value := range temps {
		if difference := value - norm; difference < 0 {
			fmt.Printf("%d: ниже нормы на %d\n", value, -difference)
		} else if difference > 0 {
			fmt.Printf("%d: выше нормы на %d\n", value, difference)
		} else if difference == 0 {
			fmt.Printf("%d: норма\n", value)
		}
	}
}
