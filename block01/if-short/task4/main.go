// Задача 4*. Затенение переменной
//
// Дано var limit int = 10. Вывести три строки: значение limit до if,
// значение limit внутри if и значение limit после if — так, чтобы
// получился вывод ниже.
//
// Ожидаемый вывод:
//
//	До if: limit = 10
//	Внутри if: limit = 3
//	После if: limit = 10
//
// Ограничения: переменная в краткой инструкции обязана называться
// ТОЧНО ТАК ЖЕ — limit. Внешнюю переменную запрещено менять: ни
// присваивания limit = 3, ни возврата значения обратно. Обе строки
// «До if» и «После if» печатают одну и ту же переменную.
//
// В этом и подвох: внутри if имя limit занято новой переменной, а
// внешняя никуда не делась и осталась нетронутой. Это называется
// затенением (shadowing).
//
// Когда решишь — допиши в конце файла комментарием ответ на вопрос:
// почему внешняя limit осталась равна 10, хотя внутри if мы явно
// видели 3? Это не формальность: та же механика однажды заставит
// искать баг, где ошибка молча теряется в затенённой переменной err.
//
// Запуск: go run ./block01/if-short/task4
package main

import "fmt"

func main() {
	var limit int = 10

	fmt.Printf("До if: limit = %d\n", limit)

	if limit := 3; true {
		fmt.Printf("Внутри if: limit = %d\n", limit)
	}

	fmt.Printf("После if: limit = %d\n", limit)
}
