// Задача 1. Делимость на 3
//
// Даны var a int = 18 и var b int = 17. Для каждого числа проверить,
// делится ли оно на 3 без остатка. Если делится — сообщить об этом;
// если нет — сообщить и назвать остаток.
//
// Ожидаемый вывод:
//
//	18 делится на 3
//	17 не делится на 3, остаток 2
//
// Ограничения: остаток вычисляется ТОЛЬКО в краткой инструкции внутри
// if — никаких переменных, объявленных до if. Тот же остаток надо
// напечатать в ветке else: переменная из краткой инструкции видна не
// только в блоке if, но и во всех ветках else/else if этой конструкции.
//
// Запуск: go run ./block01/if-short/task1

package main

import "fmt"

func main() {
	var a int = 18
	var b int = 17

	if v := a % 3; v == 0 {
		fmt.Printf("%d делится на 3\n", a)
	} else {
		fmt.Printf("%d не делится на 3, остаток %d\n", a, v)
	}

	if v := b % 3; v == 0 {
		fmt.Printf("%d делится на 3\n", b)
	} else {
		fmt.Printf("%d не делится на 3, остаток %d\n", b, v)
	}
}
