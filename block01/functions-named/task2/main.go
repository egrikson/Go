// Задача 2. Переделка stats — та, что осталась недоделанной
//
// Это доработка block01/functions-multi/task3, где в шапке файла висит
// заметка о трёх невыполненных пунктах. Здесь закрываем все три.
//
// Написать функцию с ИМЕНОВАННЫМИ возвратами:
//
//	func stats(numbers [5]int) (sum, min, max int)
//
// Вызвать её ДВАЖДЫ:
//  1. взять все три значения и напечатать одной строкой;
//  2. взять только максимум, остальные два отбросить через _.
//
// Вход: [5]int{12, 45, 7, 23, 38}
//
// Ожидаемый вывод:
//
//	Сумма: 125, минимум: 7, максимум: 45
//	Только максимум: 45
//
// Ограничения: один цикл внутри stats; min и max начинать с
// numbers[0], а не с нуля; выход голым return.
//
// Что именно чинится по сравнению с прошлой версией:
//   - порядок возврата теперь записан в сигнатуре, перепутать нельзя;
//   - max стартует с первого элемента, поэтому массив из отрицательных
//     больше не сломает функцию;
//   - второй вызов наконец использует пустой идентификатор.
//
// Проверь себя: подставь [5]int{-4, -9, -2, -7, -5}. Должно выйти
// «Сумма: -27, минимум: -9, максимум: -2». Старая версия вернула бы
// максимум 0, которого в массиве нет.
//
// Запуск: go run ./block01/functions-named/task2
package main

import "fmt"

func main() {
	data := [5]int{12, 45, 7, 23, 38}

	sumData, minData, maxData := stats(data)
	fmt.Printf("Сумма: %d, минимум: %d, максимум: %d\n", sumData, minData, maxData)

	_, _, maxData2 := stats(data)
	fmt.Printf("Только максимум: %d", maxData2)
}

func stats(numbers [5]int) (sum, min, max int) {
	min = numbers[0]
	max = numbers[0]

	for _, value := range numbers {
		sum += value
		if min > value {
			min = value
		}

		if max < value {
			max = value
		}
	}
	return
}
