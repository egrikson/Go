// Задача 3. Поиск: когда ноль — плохой ответ
//
// Написать функцию поиска элемента в массиве:
//
//	func find(numbers [5]int, target int) (index int, found bool)
//
// Если элемент найден — вернуть его индекс и true. Если нет — вернуть
// -1 и false.
//
// Вход: [5]int{12, 45, 7, 23, 38}, искать 7, затем 99, затем 12.
//
// Ожидаемый вывод:
//
//	7: найдено на позиции 2
//	99: не найдено
//	12: найдено на позиции 0
//
// Ограничения: результат проверять краткой конструкцией
// if i, ok := find(...); ok — той самой из block01/if-short;
// перебор целей — через for range по массиву из трёх чисел.
//
// ГЛАВНОЕ В ЭТОЙ ЗАДАЧЕ. Именованные возвраты создаются с нулевыми
// значениями, и голый return вернул бы (0, false). Заманчиво на этом
// сэкономить — но посмотри на третью строку ожидаемого вывода: число
// 12 лежит на позиции 0. Если «не найдено» тоже возвращает 0, эти два
// случая становятся неразличимы по индексу.
//
// Поэтому для «не найдено» нужен индекс, которого не бывает у реальных
// элементов: -1. И написать его придётся явно — голый return тут не
// подходит.
//
// Вывод, который стоит забрать: нулевое значение годится как метка
// «пусто» только тогда, когда оно заведомо невозможно среди настоящих
// данных. Для индексов массива ноль возможен, для делителя числа —
// нет (вспомни divisor := 0 в задаче про простые числа).
//
// Запуск: go run ./block01/functions-named/task3
package main

import "fmt"

func main() {
	data := [5]int{12, 45, 7, 23, 38}
	dataTest := []int{7, 99, 12, 23, 38, 100}

	for _, testFindData := range dataTest {
		if i, ok := find(data, testFindData); ok {
			fmt.Printf("%d: найдено на позиции %d\n", testFindData, i)
		} else {
			fmt.Printf("%d: не найдено\n", testFindData)
		}
	}
}

func find(numbers [5]int, target int) (index int, found bool) {
	for index = 0; index < len(numbers); index++ {
		if numbers[index] == target {
			found = true
			return
		}
	}
	return -1, false
}
