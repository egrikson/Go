// Задача 3. Матрица: суммы строк и максимум
//
// Дана матрица 3x4:
//
//	matrix := [3][4]int{
//		{3, 7, 1, 9},
//		{4, 2, 8, 6},
//		{5, 11, 0, 2},
//	}
//
// Для каждой строки вывести её номер и сумму элементов, а затем найти
// максимальный элемент во всей матрице и его позицию.
//
// Ожидаемый вывод:
//
//	Строка 0: сумма 20
//	Строка 1: сумма 20
//	Строка 2: сумма 18
//	Максимум: 11 в позиции [2][1]
//
// Ограничения: вложенные циклы через for range; максимум и его позицию
// искать сравнениями, не вписывать числом — при других значениях в
// матрице ответ обязан остаться верным. Размеры 3 и 4 в коде не
// фигурируют: range сам знает, сколько элементов обходить.
//
// Запуск: go run ./ch02/2.12/task3
package main

import "fmt"

func main() {
	matrix := [3][4]int{
		{3, 7, 1, 9},
		{4, 2, 8, 6},
		{5, 11, 0, 2},
	}

	maxNum := matrix[0][0]
	var maxI, maxJ int

	for i, row := range matrix {
		sumRow := 0

		for j, value := range row {
			sumRow += value

			if value > maxNum {
				maxNum = value
				maxI = i
				maxJ = j
			}
		}

		fmt.Printf("Строка %d: сумма %d\n", i, sumRow)
	}
	fmt.Printf("Максимум: %d в позиции [%d][%d]\n", maxNum, maxI, maxJ)
}
