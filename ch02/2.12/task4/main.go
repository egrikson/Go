// Задача 4*. Пара с нужной суммой — выход из двух циклов сразу
//
// Даны два массива и целевая сумма:
//
//	var a = [4]int{2, 7, 11, 15}
//	var b = [4]int{1, 3, 6, 9}
//	const target int = 13
//
// Найти ПЕРВУЮ пару (элемент из a, элемент из b), дающую в сумме target,
// перебирая a внешним циклом, b — внутренним. Как только пара найдена,
// перебор должен прекратиться полностью. Заодно посчитать, сколько пар
// было проверено до остановки.
//
// Ожидаемый вывод:
//
//	Ищем пару с суммой 13
//	Найдено: 7 + 6 = 13 (индексы 1 и 2)
//	Проверено пар: 7
//
// Ограничения: выход из обоих циклов — через метку (label), никаких
// вспомогательных флагов вроде found bool и никаких проверок «если уже
// нашли — пропустить» во внешнем цикле.
//
// Счётчик проверенных пар здесь — не украшение, а способ себя проверить.
// Всего пар 16. Если написать обычный break во внутреннем цикле, внешний
// продолжит работать и счётчик покажет 15 вместо 7. Совпало 7 — значит
// метка отработала и перебор действительно оборвался.
//
// Запуск: go run ./ch02/2.12/task4
package main

import "fmt"

func main() {
	var a = [4]int{2, 7, 11, 15}
	var b = [4]int{1, 3, 6, 9}
	const target int = 13
	var count int

	fmt.Println("Ищем пару с суммой", target)

outer:
	for i := 0; i < len(a); i++ {
		for j := 0; j < len(b); j++ {
			count++
			if a[i]+b[j] == target {
				fmt.Printf("Найдено: %d + %d = %d (индексы %d и %d)\n", a[i], b[j], target, i, j)
				break outer
			}
		}
	}
	fmt.Println("Проверено пар:", count)
}
