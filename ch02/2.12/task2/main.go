// Задача 2. Разбор массива: continue и break
//
// Дан массив var data = [8]int{5, 0, 12, 0, -3, 7, -9, 4}. Вывести:
//
//  1. сам массив;
//  2. сумму только положительных чисел — нули и отрицательные пропускать
//     через continue;
//  3. количество нулей;
//  4. первое отрицательное число и его индекс — поиск остановить сразу
//     после находки через break, дальше массив не просматривать.
//
// Ожидаемый вывод:
//
//	Массив: [5 0 12 0 -3 7 -9 4]
//	Сумма положительных: 28
//	Нулей: 2
//	Первое отрицательное: -3 на индексе 4
//
// Ограничения: перебор — через for range (индекс и значение сразу);
// пропуск элементов — обязательно через continue, а не через вложенный
// if вокруг всего тела; поиск первого отрицательного — отдельный цикл
// с break. Индексы руками не писать: ответ «4» программа должна найти
// сама и остаться верной при других числах в массиве.
//
// Запуск: go run ./ch02/2.12/task2
package main

import "fmt"

func main() {
	var data = [8]int{5, 0, 12, 0, -3, 7, -9, 4}

	var sumPositive int
	var countZero int

	for _, value := range data {
		if value == 0 {
			countZero++
			continue
		}
		if value < 0 {
			continue
		}
		sumPositive += value
	}

	fmt.Println("Массив:", data)
	fmt.Println("Сумма положительных:", sumPositive)
	fmt.Println("Нулей:", countZero)

	for i, value := range data {
		if value < 0 {
			fmt.Printf("Первое отрицательное: %d на индексе %d\n", value, i)
			break
		}
	}
}
