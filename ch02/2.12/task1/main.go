// Задача 1. Квадраты и их сумма
//
// Для чисел от 1 до 6 вывести само число и его квадрат в формате
// «число -> квадрат», а после цикла — сумму всех квадратов.
//
// Ожидаемый вывод:
//
//	1 -> 1
//	2 -> 4
//	3 -> 9
//	4 -> 16
//	5 -> 25
//	6 -> 36
//	Сумма квадратов: 91
//
// Ограничения: один классический цикл for со счётчиком; верхнюю границу
// задать константой и использовать её в условии цикла, а не писать 6
// прямо в for — поменяв константу на 10, программа должна отработать без
// других правок. Сумма накапливается в переменной по ходу цикла, а не
// считается формулой.
//
// Запуск: go run ./ch02/2.12/task1
package main

import "fmt"

func main() {
	const limit int = 6

	var sum int

	for i := 1; i <= limit; i++ {
		x := i * i

		fmt.Printf("%d -> %d\n", i, x)
		sum += x
	}

	fmt.Println("Сумма квадратов:", sum)
}
