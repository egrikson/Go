// Задача 4*. Обмен значений через XOR, без временной переменной
//
// Даны var a int = 12, b int = 25. Вывести исходные значения, затем
// обменять значения a и b местами, используя ТОЛЬКО оператор ^ (три
// последовательные операции присваивания вида a = a ^ b), и вывести
// результат.
//
// Ожидаемый вывод:
//
//	До обмена: a=12, b=25
//	После обмена: a=25, b=12
//
// Ограничения: никаких дополнительных переменных; обмен — ровно тремя
// строками через ^ (без +, -, *, без временной переменной).
//
// Запуск: go run ./ch02/2.8/task4
package main

import "fmt"

func main() {
	var a int = 12
	var b int = 25

	fmt.Printf("До обмена: a=%d, b=%d\n", a, b)

	a = a ^ b
	b = a ^ b
	a = b ^ a

	fmt.Printf("После обмена: a=%d, b=%d\n", a, b)
}
