// Задача 4*. Точность float32 против float64
//
// Даны:
//
//	var a float32 = 0.1
//	var b float64 = 0.1
//
// Вывести оба числа с точностью до 10 знаков после запятой, чтобы
// наглядно показать разницу в точности между float32 и float64.
//
// Ожидаемый вывод:
//
//	float32: 0.1000000015
//	float64: 0.1000000000
//
// Ограничения: кроме двух заданных переменных a и b — никаких других
// переменных не заводить; ровно два вызова fmt.Printf; никаких
// арифметических операций (тема ещё не пройдена) — только форматирование.
//
// Запуск: go run ./ch02/2.5/task4
package main

import "fmt"

func main() {
	var a float32 = 0.1
	var b float64 = 0.1

	fmt.Printf("float32: %.10f\n", a)
	fmt.Printf("float64: %.10f\n", b)
}
