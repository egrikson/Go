// Задача 2. Чек в магазине
//
// Даны три товара и их цены:
//
//	"Хлеб"   45.5
//	"Молоко" 89.99
//	"Сыр"    350.0
//
// Вывести их построчно так, чтобы название было прижато влево и занимало
// ровно 12 символов, а цена — прижата вправо, занимала ровно 8 символов
// и печаталась с двумя знаками после запятой.
//
// Ожидаемый вывод:
//
//	Хлеб           45.50
//	Молоко         89.99
//	Сыр           350.00
//
// Ограничения: выравнивание и точность задаются флагами формата в самой
// строке формата (ширина и precision), а не вручную дописанными пробелами.
//
// Запуск: go run ./ch02/2.5/task2
package main

import "fmt"

func main() {
	var bread string = "Хлеб"
	var milk string = "Молоко"
	var cheese string = "Сыр"

	var priceBread float64 = 45.5
	var priceMilk float64 = 89.99
	var priceCheese float64 = 350.0

	fmt.Printf("%-12s%8.2f\n", bread, priceBread)
	fmt.Printf("%-12s%8.2f\n", milk, priceMilk)
	fmt.Printf("%-12s%8.2f\n", cheese, priceCheese)
}
