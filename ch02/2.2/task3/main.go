// Задача 3. Регистр имеет значение
//
// Часть 1: объявить две переменные, различающиеся только регистром первой
// буквы, дать им разные значения и вывести обе.
//
// Часть 2: обменять значения двух других переменных через третью,
// временную.
//
// Вывести:
//
//	hello и Hello — разные переменные
//	первая: первое значение
//	вторая: второе значение
//	до обмена: A B
//	после обмена: B A
//
// Ограничения: обмен только через временную переменную, множественное
// присваивание пока не использовать.
//
// Запуск: go run ./ch02/2.2/task3
package main

import "fmt"

func main() {
	//Часть 1
	fmt.Println("Часть 1:")
	fmt.Println("===========================================")

	var hello, Hello string
	hello = "hello"
	Hello = "Hello"

	fmt.Println("Вывод переменной hello >>> ", hello)
	fmt.Println("Вывод переменной Hello >>> ", Hello)

	fmt.Println("===========================================")
	fmt.Println()

	//Часть 2
	fmt.Println("Часть 2:")
	fmt.Println("===========================================")

	var temp string
	temp = hello
	hello = Hello
	Hello = temp

	fmt.Println("Вывод переменной hello >>> ", hello)
	fmt.Println("Вывод переменной Hello >>> ", Hello)

	fmt.Println("===========================================")
}
