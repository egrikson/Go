// Задача 1. Простой чек
//
// Даны var a int = 17, b int = 5. Вычислить и вывести сумму, разность,
// произведение, частное от целочисленного деления и остаток от деления
// a на b.
//
// Ожидаемый вывод:
//
//	Сумма: 22
//	Разность: 12
//	Произведение: 85
//	Частное: 3
//	Остаток: 2
//
// Ограничения: только int, вывод через fmt.Println.
//
// Запуск: go run ./ch02/2.6/task1
package main

import "fmt"

func main() {
	var a int = 17
	var b int = 5
	fmt.Println("Сумма:", a+b)
	fmt.Println("Разность:", a-b)
	fmt.Println("Произведение:", a*b)
	fmt.Println("Частное:", a/b)
	fmt.Println("Остаток:", a%b)
}
