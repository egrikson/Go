// Задача 4*. Сумма цифр без лишних переменных
//
// Дано const n int = 487 (трёхзначное число). Вывести сумму его цифр.
//
// Ожидаемый вывод:
//
//	Сумма цифр числа 487: 19
//
// Ограничения: кроме n — никаких дополнительных переменных (никаких
// hundreds/tens/ones); сумма цифр вычисляется одним арифметическим
// выражением прямо внутри единственного вызова fmt.Println, используя
// только / и % над n.
//
// Запуск: go run ./ch02/2.6/task4
package main

import "fmt"

func main() {
	const n int = 487
	fmt.Printf("Сумма цифр числа %d: %d", n, n/10%10+n/100+n%10)
}
