// Задача 3. Диагонали матрицы
//
// Дана матрица 3x3:
//
//	matrix := [3][3]int{
//		{1, 2, 3},
//		{4, 5, 6},
//		{7, 8, 9},
//	}
//
// Вывести матрицу, число строк и столбцов, сумму главной диагонали
// (1+5+9) и сумму побочной (3+5+7). Затем удвоить центральный элемент
// через составной оператор присвоения и вывести матрицу и главную
// диагональ заново.
//
// Ожидаемый вывод:
//
//	Матрица: [[1 2 3] [4 5 6] [7 8 9]]
//	Строк: 3, столбцов: 3
//	Главная диагональ: 15
//	Побочная диагональ: 15
//	После matrix[1][1] *= 2: [[1 2 3] [4 10 6] [7 8 9]]
//	Главная диагональ: 20
//
// Ограничения: число строк и столбцов получать через len() (для столбцов
// — len от первой строки), а не писать 3 руками; удвоение центрального
// элемента — только через *=, не через matrix[1][1] = 10. Без циклов.
//
// Запуск: go run ./ch02/2.10/task3
package main

import "fmt"

func main() {
	matrix := [3][3]int{
		{1, 2, 3},
		{4, 5, 6},
		{7, 8, 9},
	}

	fmt.Println("Матрица:", matrix)
	fmt.Printf("Строк: %d, столбцов: %d\n", len(matrix), len(matrix[0]))
	fmt.Println("Главная диагональ:", matrix[0][0]+matrix[1][1]+matrix[2][2])
	fmt.Println("Побочная диагональ:", matrix[0][2]+matrix[1][1]+matrix[2][0])

	matrix[1][1] *= 2

	fmt.Println("После matrix[1][1] *= 2:", matrix)
	fmt.Println("Главная диагональ:", matrix[0][0]+matrix[1][1]+matrix[2][2])
}
