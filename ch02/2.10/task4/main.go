// Задача 4*. Копия или не копия
//
// Даны три массива:
//
//	nums1 := [4]int{3, 4, 5, 6}
//	nums2 := nums1
//	nums3 := [4]int{3, 4, 5}
//
// Вывести результат сравнения nums1 и nums2. Затем уменьшить последний
// элемент nums2 на 6 (составным оператором присвоения) и вывести оба
// массива, а также результаты сравнений nums2 с nums3 и nums1 с nums3.
//
// Ожидаемый вывод:
//
//	nums1 == nums2: true
//	После nums2[3] -= 6:
//	nums1: [3 4 5 6]
//	nums2: [3 4 5 0]
//	nums2 == nums3: true
//	nums1 == nums3: false
//
// Прежде чем запускать — предскажи вывод на бумаге. Две строки из шести
// удивляют почти всех: почему nums1 не изменился и почему nums2 вдруг
// стал равен nums3, хотя объявлены они по-разному.
//
// Ограничения: никаких дополнительных переменных кроме этих трёх
// массивов; изменение элемента — только через -=; последний индекс
// вычислять через len(). Без циклов и без if.
//
// Запуск: go run ./ch02/2.10/task4
package main

import "fmt"

func main() {
	nums1 := [4]int{3, 4, 5, 6}
	nums2 := nums1
	nums3 := [4]int{3, 4, 5}

	fmt.Println("nums1 == nums2:", nums1 == nums2)

	nums2[3] -= 6

	fmt.Println("После nums2[3] -= 6:")
	fmt.Println("nums1:", nums1)
	fmt.Println("nums2:", nums2)
	fmt.Println("nums2 == nums3:", nums2 == nums3)
	fmt.Println("nums1 == nums3:", nums1 == nums3)
}
