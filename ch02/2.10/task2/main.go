// Задача 2. Нули, которых не ждали
//
// Дан массив на 5 оценок, но заполнены только три:
// var grades = [5]int{5, 4, 5}. Вывести массив, его длину, сумму всех
// элементов, среднее по всей длине массива и среднее только по трём
// выставленным оценкам.
//
// Смысл задачи — увидеть, что незаполненные элементы не «пустые»:
// они равны нулю и молча портят среднее.
//
// Ожидаемый вывод:
//
//	grades: [5 4 5 0 0]
//	Длина массива: 5
//	Сумма: 14
//	Среднее по всей длине: 2
//	Среднее по трём оценкам: 4
//
// Ограничения: сумму считать поэлементно (циклов ещё нет); деление
// целочисленное, дробную часть не выводить; длину брать через len().
//
// Запуск: go run ./ch02/2.10/task2
package main

import "fmt"

func main() {
	var grades = [5]int{5, 4, 5}

	var sumGrades int = grades[0] + grades[1] + grades[2] + grades[3] + grades[4]
	var lenGrades int = len(grades)

	fmt.Println("grades:", grades)
	fmt.Println("Длина массива:", lenGrades)
	fmt.Println("Сумма:", sumGrades)
	fmt.Println("Среднее по всей длине:", sumGrades/lenGrades)
	fmt.Println("Среднее по трём оценкам:", sumGrades/3)
}
