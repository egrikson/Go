// Задача 1. Массив температур
//
// Дан массив var temps = [...]int{12, 15, 9, 21, 18}. Вывести сам массив,
// его длину, первый и последний элементы, затем изменить третий элемент
// (индекс 2) на 30 и вывести массив ещё раз.
//
// Ожидаемый вывод:
//
//	Массив: [12 15 9 21 18]
//	Длина: 5
//	Первый: 12
//	Последний: 18
//	После temps[2] = 30: [12 15 30 21 18]
//
// Ограничения: длину получать через len(); последний элемент доставать
// не по числу 4, а вычислением от len() — чтобы работало при любой длине
// массива. Без циклов и без if (они ещё не пройдены).
//
// Запуск: go run ./ch02/2.10/task1
package main

import "fmt"

func main() {
	var temps = [...]int{12, 15, 9, 21, 18}
	fmt.Println("Массив:", temps)
	fmt.Println("Длина:", len(temps))
	fmt.Println("Первый:", temps[0])
	fmt.Println("Последний:", temps[len(temps)-1])

	temps[2] = 30

	fmt.Println("После temps[2] = 30:", temps)
}
