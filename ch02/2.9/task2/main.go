// Задача 2. Побитовые присвоения
//
// Дано var y int = 6. Последовательно применить: <<= 2, >>= 1, &= 9,
// ^= 5, |= 2. После каждого шага печатать текущее значение y.
//
// Ожидаемый вывод:
//
//	y <<= 2: 24
//	y >>= 1: 12
//	y &= 9: 8
//	y ^= 5: 13
//	y |= 2: 15
//
// Ограничения: только <<=, >>=, &=, ^=, |=.
//
// Запуск: go run ./ch02/2.9/task2
package main

import "fmt"

func main() {
	var y int = 6

	y <<= 2
	fmt.Printf("y <<= 2: %d\n", y)

	y >>= 1
	fmt.Printf("y >>= 1: %d\n", y)

	y &= 9
	fmt.Printf("y &= 9: %d\n", y)

	y ^= 5
	fmt.Printf("y ^= 5: %d\n", y)

	y |= 2
	fmt.Printf("y |= 2: %d\n", y)
}
