// Задача 1. Цепочка присвоений
//
// Дано var x int = 20. Последовательно применить: += 15, -= 8, *= 3,
// /= 4, %= 7. После каждого шага печатать текущее значение x.
//
// Ожидаемый вывод:
//
//	x += 15: 35
//	x -= 8: 27
//	x *= 3: 81
//	x /= 4: 20
//	x %= 7: 6
//
// Ограничения: только операторы присвоения (+=, -=, *=, /=, %=),
// никаких промежуточных переменных.
//
// Запуск: go run ./ch02/2.9/task1
package main

import "fmt"

func main() {
	var x int = 20

	x += 15
	fmt.Printf("x += 15: %d\n", x)

	x -= 8
	fmt.Printf("x -= 8: %d\n", x)

	x *= 3
	fmt.Printf("x *= 3: %d\n", x)

	x /= 4
	fmt.Printf("x /= 4: %d\n", x)

	x %= 7
	fmt.Printf("x %%= 7: %d\n", x)
}
