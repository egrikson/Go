// Задача 3. Приоритет внутри правой части
//
// Дано var total int = 50. Последовательно выполнить (без скобок):
//
//	total += 3 * 4 - 2
//	total -= 20 / 4 + 1
//	total *= 2 + 1
//	total %= 10 * 5 - 40
//
// После каждой строки печатать total.
//
// Ожидаемый вывод:
//
//	total += 3 * 4 - 2: 60
//	total -= 20 / 4 + 1: 54
//	total *= 2 + 1: 162
//	total %= 10 * 5 - 40: 2
//
// Ограничения: не добавлять скобки — вся правая часть оператора
// присвоения вычисляется как единое выражение по обычному приоритету
// арифметики (*, /, % раньше +, -), и только потом объединяется с total.
//
// Запуск: go run ./ch02/2.9/task3
package main

import "fmt"

func main() {
	var total int = 50

	total += 3*4 - 2
	fmt.Printf("total += 3 * 4 - 2: %d\n", total)

	total -= 20/4 + 1
	fmt.Printf("total -= 20 / 4 + 1: %d\n", total)

	total *= 2 + 1
	fmt.Printf("total *= 2 + 1: %d\n", total)

	total %= 10*5 - 40
	fmt.Printf("total %%= 10 * 5 - 40: %d\n", total)
}
