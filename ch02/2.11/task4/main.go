// Задача 4*. Накопительные права доступа
//
// Дано var level int = 2. Уровни доступа устроены накопительно: чем выше
// уровень, тем больше прав, и все права нижних уровней тоже действуют.
//
//	уровень 3 — может удалять, редактировать и читать
//	уровень 2 — может редактировать и читать
//	уровень 1 — может читать
//	остальное — нет доступа
//
// Вывести уровень и все права, которые он даёт, по одному в строке,
// сверху вниз — от старшего права к младшему.
//
// Ожидаемый вывод:
//
//	Уровень доступа: 2
//	Может редактировать
//	Может читать
//
// Ограничения: ровно ОДИН switch, никаких if; каждая строка про право
// («Может удалять», «Может редактировать», «Может читать») написана
// в коде ровно один раз — копипастить их по веткам нельзя. Уровень 3
// должен печатать все три строки, уровень 1 — одну, уровень 0 или 5 —
// «Нет доступа».
//
// Подсказка: в switch есть оператор, который передаёт управление
// следующему case, не проверяя его условие. Здесь он не костыль,
// а именно то, ради чего он придуман.
//
// Проверь себя: подставь level = 3, потом level = 1, потом level = 7.
//
// Запуск: go run ./ch02/2.11/task4
package main

import "fmt"

func main() {
	var level int = 2

	fmt.Println("Уровень доступа:", level)

	switch level {
	case 3:
		fmt.Println("Может удалять")
		fallthrough
	case 2:
		fmt.Println("Может редактировать")
		fallthrough
	case 1:
		fmt.Println("Может читать")
	default:
		fmt.Println("Нет доступа")
	}
}
